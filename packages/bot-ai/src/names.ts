/** Picks a random bot name not already used in the lobby. */
export function randomBotName(takenNames: string[], rng: () => number = Math.random): string {
  const taken = new Set(takenNames.map((n) => n.trim().toLowerCase()))
  const available = BOT_NAME_POOL.filter((n) => !taken.has(n.toLowerCase()))
  if (available.length > 0) {
    return available[Math.floor(rng() * available.length)]!
  }
  const base = BOT_NAME_POOL[Math.floor(rng() * BOT_NAME_POOL.length)]!
  return `${base} ${Math.floor(rng() * 90) + 10}`
}
